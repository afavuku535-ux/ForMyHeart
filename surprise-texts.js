// (به‌جای نوشتن دستی ۱۰۰۰ خط، از ترکیب هوشمند استفاده شده تا
//  هم تنوع واقعی داشته باشه هم تکراری نباشه)
// ============================================================

function generateSurpriseTexts() {
  const openers = [
    "هر روز که می‌گذره", "هر بار که بهت فکر می‌کنم", "وقتی اسمت میاد وسط ذهنم",
    "توی شلوغی روزم", "همین الان که این رو می‌نویسم", "قبل از خواب",
    "صبح که بیدار می‌شم", "میون هزار فکر مختلف", "توی سکوت شب",
    "با هر پیامی که ازت می‌رسه", "بین این همه آدم دنیا", "وقتی خسته‌ام",
    "حتی توی روزای بد", "لای همه‌ی خاطره‌هام", "وقتی چشمامو می‌بندم",
    "توی راه برگشت به خونه", "زیر بارون", "توی یه غروب ساده",
    "وسط یه روز عادی", "وقتی صدات توی سرمه"
  ];

  const feelings = [
    "دلم آروم می‌گیره", "لبخند میاد رو لبم", "قلبم گرم می‌شه",
    "همه‌چیز قشنگ‌تر می‌شه", "دنیا رنگ دیگه‌ای می‌گیره", "نفسم راحت‌تر می‌شه",
    "یه حس امنیت میاد سراغم", "دلتنگت می‌شم", "شکرگزار داشتنت می‌شم",
    "می‌فهمم چقدر خوش‌شانسم", "بی‌قرار دیدنت می‌شم", "یاد لبخندت می‌افتم",
    "دلم برای صدات تنگ می‌شه", "حس می‌کنم همه‌چی روبه‌راهه", "آروم می‌شم"
  ];

  const middles = [
    "چون می‌دونم یه نفر مثل تو کنارمه",
    "و می‌فهمم داشتنت یعنی چی",
    "و باز هم قدر این حس رو می‌دونم",
    "و به این فکر می‌کنم که چقدر خوبه بودنت",
    "و یاد همه‌ی روزای خوبمون می‌افتم",
    "و می‌دونم این حس، حس آدم‌های معمولی نیست",
    "و دلم می‌خواد این حس هیچ‌وقت تموم نشه",
    "چون تو یه جور دیگه‌ای مهمی",
    "و دوباره عاشق همین سادگیت می‌شم",
    "و به این نتیجه می‌رسم که کنار تو بودن قشنگ‌ترین اتفاقه"
  ];

  const closers = [
    "دوستت دارم، همین‌قدر ساده و همین‌قدر واقعی. ❤️",
    "ممنونم که هستی. 🧡",
    "تو بهترین اتفاق این روزای منی. 💛",
    "خوشحالم که تو زندگیمی. ❤️",
    "امیدوارم همیشه کنار هم باشیم. 🤍",
    "قدرت رو می‌دونم، همیشه. ❤️",
    "بی‌تعارف، بهترینی. 💖",
    "این حس رو با هیچی عوض نمی‌کنم. ❤️",
    "خوشحالم که دستمو گرفتی. 🧡",
    "می‌خوام همیشه این‌جوری بمونیم. 💛",
    "هیچ‌وقت این حس رو ازم نگیر. ❤️",
    "تو خونه‌ی آرامش منی. 🤍"
  ];

  const set = new Set();
  const result = [];

  // ترکیب تصادفی تا رسیدن به ۱۰۰۰ متن یکتا
  let guard = 0;
  while (result.length < 1000 && guard < 200000) {
    guard++;
    const o = openers[Math.floor(Math.random() * openers.length)];
    const f = feelings[Math.floor(Math.random() * feelings.length)];
    const m = middles[Math.floor(Math.random() * middles.length)];
    const c = closers[Math.floor(Math.random() * closers.length)];
    const text = `${o}، ${f}، ${m}. ${c}`;
    if (!set.has(text)) {
      set.add(text);
      result.push(text);
    }
  }
  return result;
}

